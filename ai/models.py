from dataclasses import dataclass, field


@dataclass(slots=True)
class AIPrompt:
    """
    Represents the prompts that will be sent to an LLM.

    The system prompt defines the model's behavior, while the
    user prompt contains the execution analysis generated by
    SparkLens.
    """

    system_prompt: str
    user_prompt: str


@dataclass(slots=True)
class AIConfig:
    """
    Configuration for an AI provider.
    """

    api_key: str
    model: str = "gemini-2.5-flash"
    temperature: float = 0.2


@dataclass(slots=True)
class AIExplanation:
    """
    Structured explanation returned by the AI provider.

    Attributes:
        summary:
            A concise overview of the execution plan.

        explanation:
            A detailed explanation of the execution flow,
            performance characteristics, and analysis findings.

        recommendations:
            Optimization suggestions generated by the AI.

        model:
            Name of the LLM used to generate the explanation.
    """

    summary: str
    explanation: str
    recommendations: list[str] = field(default_factory=list)
    model: str = ""