from dataclasses import dataclass, field


@dataclass(slots=True)
class AIPrompt:
    """
    Represents the prompts that will be sent to an LLM.

    The system prompt defines the model's behavior, while the
    user prompt contains the execution analysis generated by
    SparkLens.
    """

    system_prompt: str
    user_prompt: str


@dataclass(slots=True)
class AIConfig:
    """
    Configuration for an AI provider.
    """

    api_key: str
    model: str = "gemini-2.5-flash"
    temperature: float = 0.2

@dataclass(slots=True)
class AIInsight:
    category: str
    title: str
    description: str

@dataclass(slots=True)
class AIExplanation:
    summary: str
    explanation: str
    recommendations: list[str] = field(default_factory=list)
    insights: list[AIInsight] = field(default_factory=list)
    model: str = ""


