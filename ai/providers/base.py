from abc import ABC, abstractmethod

from ai.models import AIConfig, AIExplanation, AIPrompt


class AIProvider(ABC):
    """
    Abstract base class for all AI providers.

    Every provider is responsible for:
        1. Sending prompts to its underlying LLM.
        2. Parsing the LLM response.
        3. Returning a structured AIExplanation.
    """

    def __init__(self, config: AIConfig):
        self._config = config

    @abstractmethod
    def generate(self, prompt: AIPrompt) -> AIExplanation:
        """
        Generates an AI explanation for the supplied prompt.

        Args:
            prompt: Prompt generated by PromptBuilder.

        Returns:
            A structured AIExplanation.
        """
        raise NotImplementedError