from ai.models import AIExplanation
from ai.prompt_builder import PromptBuilder
from ai.providers.base import AIProvider
from models.analysis_result import AnalysisResult


class Explainer:
    """
    Orchestrates the AI explanation pipeline.

    Pipeline:
        AnalysisResult
            ↓
        PromptBuilder
            ↓
        AIProvider
            ↓
        AIExplanation
    """

    def __init__(self, provider: AIProvider):
        self._provider = provider

    def explain(self, result: AnalysisResult) -> AIExplanation:
        """
        Generates an AI explanation for the supplied analysis result.

        Args:
            result:
                The deterministic analysis generated by SparkLens.

        Returns:
            A structured AIExplanation.
        """
        prompt = PromptBuilder.build(result)
        return self._provider.generate(prompt)